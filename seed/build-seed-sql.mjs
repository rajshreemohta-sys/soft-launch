// Turns seed/accounts.json into seed/seed.sql (idempotent: skips existing companies).
import { readFileSync, writeFileSync } from "node:fs";

const accounts = JSON.parse(readFileSync(new URL("./accounts.json", import.meta.url), "utf8"));
const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;

const rows = accounts.map((a) =>
  `  (${q(a.company_name)}, ${arr(a.search_terms)}, ${q(a.sector)}, ${q(a.deal_stage)}, ${q(a.arjun_notes)}, ${q(a.last_contact_date)}::date, ${q(a.relationship_read)})`
);

writeFileSync(
  new URL("./seed.sql", import.meta.url),
  `-- Generated by seed/build-seed-sql.mjs from seed/accounts.json. Do not edit by hand.
-- Demo project. Companies and news are real; Arjun, his product and all deal notes are fictional.
insert into accounts (company_name, search_terms, sector, deal_stage, arjun_notes, last_contact_date, relationship_read) values
${rows.join(",\n")}
on conflict (company_name) do nothing;
`
);

const stages = {};
for (const a of accounts) stages[a.deal_stage] = (stages[a.deal_stage] ?? 0) + 1;
console.log(accounts.length, "accounts", stages);
